import "server-only";

/**
 * Storage abstraction.
 *
 * The application never touches a filesystem path or an S3 client directly;
 * it works with opaque storage keys. Two drivers are provided:
 *
 *  - `local`  : files on a mounted volume (default for development and for
 *                single-server deployments).
 *  - `s3`     : any S3-compatible object store (AWS S3, MinIO, R2, ...).
 *
 * Product images and prescription documents live in separate key namespaces
 * (`products/` and `prescriptions/`) so that a misconfigured bucket policy or
 * a route bug cannot expose a private document.
 */

export const STORAGE_NAMESPACE = {
  PRODUCTS: "products",
  PRESCRIPTIONS: "prescriptions",
} as const;

export type StorageNamespace = (typeof STORAGE_NAMESPACE)[keyof typeof STORAGE_NAMESPACE];

export interface StoredObject {
  key: string;
  bytes: number;
  contentType: string;
}

export interface LoadedObject {
  body: Uint8Array;
  contentType: string;
  bytes: number;
}

export interface StorageProvider {
  readonly driver: "local" | "s3";
  put(key: string, data: Buffer, contentType: string): Promise<StoredObject>;
  get(key: string): Promise<LoadedObject | null>;
  delete(key: string): Promise<void>;
  exists(key: string): Promise<boolean>;
  /** Public URL for objects in the public (product image) namespace. */
  publicUrl(key: string): string | null;
}

/**
 * Rejects keys that could escape the storage root or address another
 * namespace. Keys are generated by the application, but this is the last line
 * of defence against path traversal.
 */
export function assertSafeKey(key: string): void {
  if (!key || key.length > 512) {
    throw new Error("Invalid storage key.");
  }
  if (key.includes("\0")) {
    throw new Error("Invalid storage key.");
  }
  if (key.startsWith("/") || key.startsWith("\\")) {
    throw new Error("Invalid storage key.");
  }
  if (key.includes("..") || key.includes("//")) {
    throw new Error("Invalid storage key.");
  }
  if (!/^[A-Za-z0-9._/-]+$/.test(key)) {
    throw new Error("Invalid storage key.");
  }
  const segments = key.split("/");
  if (segments.some((segment) => segment.length === 0 || segment === "." || segment === "..")) {
    throw new Error("Invalid storage key.");
  }
  if (!Object.values(STORAGE_NAMESPACE).includes(segments[0] as StorageNamespace)) {
    throw new Error("Invalid storage namespace.");
  }
}

export function buildKey(namespace: StorageNamespace, ...parts: string[]): string {
  const key = [namespace, ...parts].join("/");
  assertSafeKey(key);
  return key;
}
